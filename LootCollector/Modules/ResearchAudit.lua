local function candidateIndex()
    local byID, families, duplicates, mapped = {}, 0, 0, 0
    for b,h,m in historicalFamilies:gmatch("(%d+),(%d+),(%d+)") do
        b,h,m = tonumber(b),tonumber(h),tonumber(m)
        families = families + 1
        if byID[b] then duplicates=duplicates+1 else byID[b]="base" end
        if h and h>0 then
            if byID[h] then duplicates=duplicates+1 else byID[h]="heroic candidate";mapped=mapped+1 end
        end
        if m and m>0 then
            if byID[m] then duplicates=duplicates+1 else byID[m]="mythic candidate";mapped=mapped+1 end
        end
    end
    return byID, families, duplicates, mapped
end

function Audit:GetStatus()
    return self.referenceVersion.." | 999 upstream variant families | 0 verified live drop edges | audit only"
end

function Audit:RunAudit()
    if self.running then
        print("|cff66ccffLootCollector Research:|r Audit already running.")
        return
    end
    local byID, families, duplicates, mapped = candidateIndex()
    if families~=self.expectedFamilies or duplicates~=0 then
        self.lastReport="Source validation failed: family count or duplicate IDs"
        print("|cffff5555LootCollector Research:|r "..self.lastReport)
        return
    end
    local discoveries=L.GetDiscoveriesDB and L:GetDiscoveriesDB() or {}
    local rc=L:GetModule("RareChest",true)
    local rares=rc and rc.GetRecords and rc:GetRecords() or {}
    if type(discoveries)~="table" then discoveries={} end
    if type(rares)~="table" then rares={} end
    local frame=self.auditFrame
    if not frame then
        frame=CreateFrame("Frame",nil,UIParent)
        self.auditFrame=frame
    end
    frame:Show()
    local state={phase=1,last=nil,scanned=0,matched=0,base=0,heroic=0,mythic=0,rareCount=0,dropText=0}
    self.running=true
    self.lastReport="Scanning saved discoveries in small batches..."
    local function finish()
        frame:SetScript("OnUpdate",nil)
        frame:Hide()
        Audit.running=false
        -- Do not retain the candidate index, original DB tables or frame.
        byID=nil
        Audit.lastReport=string.format("Checked %d discoveries + %d rare/chest records; %d archived candidate-ID matches (base %d, heroic %d, mythic %d); %d records contain unverified free-text drop notes.",
            state.scanned,state.rareCount,state.matched,state.base,state.heroic,state.mythic,state.dropText)
        print("|cff66ccffLootCollector Research:|r "..Audit.lastReport)
        print("|cffffbb55Research note:|r "..families.." historical pending-SQL families / "..mapped.." candidate variant IDs; "..duplicates.." duplicate IDs. No live Reborn loot relations verified. No records imported, changed or shared.")
    end
    frame:SetScript("OnUpdate",function()
        local budget=75
        while budget>0 do
            local data=state.phase==1 and discoveries or rares
            local ok,k,v=pcall(next,data,state.last)
            if not ok then
                frame:SetScript("OnUpdate",nil)
                frame:Hide()
                Audit.running=false
                Audit.lastReport="Audit stopped: source data changed during scan. Retry."
                print("|cffff5555LootCollector Research:|r "..Audit.lastReport)
                return
            end
            if k==nil then
                if state.phase==2 then finish();return end
                state.phase=2;state.last=nil
            else
                state.last=k
                budget=budget-1
                if state.phase==1 then
                    state.scanned=state.scanned+1
                    if type(v)=="table" then
                        local category=byID[tonumber(v.i) or -1]
                        if category then
                            state.matched=state.matched+1
                            if category=="base" then state.base=state.base+1
                            elseif category=="heroic candidate" then state.heroic=state.heroic+1
                            else state.mythic=state.mythic+1 end
                        end
                    end
                else
                    state.rareCount=state.rareCount+1
                    if type(v)=="table" and type(v.drops)=="string" and v.drops~="" then
                        state.dropText=state.dropText+1
                    end
                end
            end
        end
    end)
end
